#!/usr/bin/env node
// Regenerates src/data/creeps.json and src/data/itemPools.json from the game's own data tables
// (the wc3data package: Warcraft III SLK files as JSON). Run after a game patch changes creeps or
// item drops:  npm i -D wc3data@latest && npm run update-game-data
//
// creeps.json:    creep unit id -> name + level (map files only store the 4-letter id)
// itemPools.json: "<class>-<level>" -> items a random drop of that class/level can be

import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { units, items } = require('wc3data')
const wc3dataVersion = require('wc3data/package.json').version

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const CREEPS = path.join(ROOT, 'src/data/creeps.json')
const POOLS = path.join(ROOT, 'src/data/itemPools.json')

// Keep hand-set extras (e.g. xpFactor) from the current file.
const previous = fs.existsSync(CREEPS) ? JSON.parse(fs.readFileSync(CREEPS, 'utf8')).creeps : {}

// ----- creeps -----
const creeps = {}
for (const [id, u] of Object.entries(units)) {
  if (u.stats?.race !== 'creeps' || u.stats?.isbldg) continue
  const name = u.text?.Name
  const level = u.stats?.level
  if (!name || typeof level !== 'number') continue
  creeps[id] = { name, level, ...(previous[id]?.xpFactor != null ? { xpFactor: previous[id].xpFactor } : {}) }
}

// ----- item pools (items that can be picked as a random drop) -----
const CLASS = { Permanent: 'permanent', Charged: 'charged', PowerUp: 'powerup', Artifact: 'artifact' }
const itemId = (name) => name.toLowerCase().replace(/\s+/g, '_')
const pools = {}
for (const it of Object.values(items)) {
  const s = it.stats ?? {}
  const cls = CLASS[s.class]
  if (!s.pickRandom || !cls || !(s.Level > 0) || !it.text?.Name) continue
  ;(pools[`${cls}-${s.Level}`] ??= []).push(itemId(it.text.Name))
}
for (const k of Object.keys(pools)) pools[k] = [...new Set(pools[k])].sort()

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)))

fs.writeFileSync(
  CREEPS,
  JSON.stringify(
    {
      _about: `Neutral creep unit types from the game data (wc3data ${wc3dataVersion}); generated by npm run update-game-data. Map files only store the 4-letter id. xpFactor (optional, hand-set): share of normal creep XP the unit gives.`,
      creeps: sorted(creeps),
    },
    null,
    1,
  ) + '\n',
)
fs.writeFileSync(
  POOLS,
  JSON.stringify(
    {
      _about: `Items a random drop of each class/level can be, keyed "<class>-<level>" (wc3data ${wc3dataVersion}); generated by npm run update-game-data.`,
      pools: sorted(pools),
    },
    null,
    1,
  ) + '\n',
)
console.log(`✓ ${Object.keys(creeps).length} creep types, ${Object.keys(pools).length} item pools (wc3data ${wc3dataVersion})`)
